#!/bin/bash
# watch_rotate.sh (v2, 2026-11-06) — Mac 侧的 Colab runtime 丢失守护（24 h runtime 上限、被回收等）。
# 与 v1 的区别：一次轮换恢复整条 line 的 chain（主 driver + 该 line 的全部 wrapper），而不是只恢复第一个 run。
#
# 每 INTERVAL 秒（参数 1，默认 120）跑一次 `colab --auth=adc sessions`：
#   - 被管理的 session 若以 "Hardware: CPU" 出现，是 proxy 连接自动建的幽灵 runtime：stop 掉并按缺失处理；
#   - 缺失的 session：先问 Tokyo keepalive 日志（一次 gcloud ssh，两段输出）它是否主动停过这个 runtime；
#       停过且最后一条 'ping ok' 行像失败（abnormally|exited rc|giving up|failed|: stop）-> 写 ALERT "FAILURE on S"，
#       从表中移除，不轮换；停过且是正常结束 -> 记 "finished on purpose" 并移除；
#       keepalive 查询本身失败 -> 本 tick 跳过该 session（v1 会把空结果当成 0 而直接轮换）；
#   - 否则轮换：建 NEXT（A100，60 s 重试，最多 4 h）、scp stage.tgz + GCS key（只传路径，从不读取内容）+ 生成的
#     restore_chain.sh，在 VM 上 setsid nohup 跑恢复（写 /content/sts2/restore.log），Mac 用短 ssh 逐次轮询到最终标记；
#     再用一条 ssh 启动整条 chain，另一条短 ssh 数进程；最后把 Tokyo keepalive、colab/sessions.txt（整行换成 NEW + 最后一个
#     wrapper 的日志）、managed.txt 指向新 session。
#   - 需人工的情况（返回 2，表行改为 #HOLD，写 ALERT）：恢复不完整 / 失败 / 轮询超时，或 NEW 上已有 driver/wrapper 在跑。
#
# 表 $D/managed.txt，v2 行格式 "SESSION LINE RUNS NEXT"：
#   RUNS = 该 line 的 run dir，按 chain 顺序逗号分隔，例：
#     sts2c a w3m-a,w4-c,w9-e sts2a2
#     sts2b3 b w3m-b,w4-d,w9-f sts2b4
#   RUNS[0] 由 w3m_line.sh 直接驱动；之后每个 run 由其 wrapper 驱动（映射见 wrapper_for；也可写成 run=wrapper.sh）。
#   v1 行（单个 run）也接受：w3m-a / w3m-b 展开成 v1 隐含的完整 chain，其它单 run 只起 driver。
#   以 '#' 开头的行被跳过；恢复不完整时脚本把该行改成 "#HOLD ..."，需人工处理后去掉 '#'。
# 日志 $D/watch.log，告警 $D/ALERT。停止：rm $D/RUN。
#
# 目录：STS2_OPS_DIR = rotate 目录（managed.txt / watch.log / ALERT / RUN / stage.tgz）；
#       STS2_SSHCFG  = colab-* Host 的 ssh_config（缺少 NEXT 的 Host 块时脚本按已有块追加一个）；
#       $(dirname STS2_OPS_DIR)/colab/sessions.txt = Mac 侧 session 表（sed OLD -> NEW）。
# 测试：DRY_RUN=1 时每个外部命令（colab/ssh/scp/gcloud）打印为 'DRY: <command>'（fd 3，默认 stdout），
#       应答由 $DRY_STUBS/<命令名> 给出，绝不执行真实命令；ONE_TICK=1 只跑一个 tick 后退出；DRY 下不 sleep。
# bash 3.2 / macOS 兼容。
set -u
# STS2_OPS_DIR 必填（rotate 目录）；2026-11-06 这一 session 的值：
#   <scratchpad>/rotate
# STS2_SSHCFG 默认 $(dirname STS2_OPS_DIR)/colab/ssh_config，即
#   <scratchpad>/colab/ssh_config
D=${STS2_OPS_DIR:?set STS2_OPS_DIR to the rotate dir (managed.txt, watch.log, ALERT, RUN, stage.tgz)}
SC=$(dirname "$D")
SSHCFG=${STS2_SSHCFG:-$SC/colab/ssh_config}
KEY=$HOME/.config/sts2train/gcs-sts2-ckpt.json          # 只作为 scp 的源路径；脚本从不读取其内容
SESS_JSON=$HOME/.config/colab-cli/sessions.json
TVM=instance-tokyo-0701-predict-raven
TPROJ="--project project-a1c77ca6-822b-4f49-916 --zone asia-northeast1-b"
BUCKET=gomoku-zero-20260816-ai-sts2train
BUNDLE0=/content/sts2/sts2train-413f510188              # RUNS[0] 的 driver bundle（与 v1 rotate() 相同）
RESTORE_MAX_S=${RESTORE_MAX_S:-7200}                    # Mac 侧等待恢复最终标记的上限（每次 gcs_pull 在 VM 上 timeout 1800 s）
I=${1:-120}; DRY=${DRY_RUN:-0}; DRY_STUBS=${DRY_STUBS:-}
[ "$DRY" = 1 ] && { exec 3>&1; }
touch "$D/RUN"
log() { echo "$(date -u +%FT%TZ) $*" >> "$D/watch.log"; }
alert() { echo "$(date) $*" >> "$D/ALERT"; }
nap() { [ "$DRY" = 1 ] || sleep "$1"; }
# x ALARM CMD ARGS... — 所有外部调用的唯一入口：perl alarm + </dev/null；DRY 模式只打印并调用 stub
x() {
  local a=$1; shift
  if [ "$DRY" = 1 ]; then
    echo "DRY: $* [alarm $a]" >&3
    if [ -n "$DRY_STUBS" ] && [ -x "$DRY_STUBS/$(basename "$1")" ]; then "$DRY_STUBS/$(basename "$1")" "${@:2}" < /dev/null; else return 0; fi
  else
    perl -e "alarm $a; exec @ARGV" "$@" < /dev/null
  fi
}
vm() { x "$1" ssh -F "$SSHCFG" "colab-$2" "$3"; }                     # vm ALARM SESSION CMD（同一 runtime 永远只有一条 ssh）
tokyo() { x "$1" gcloud compute ssh $TVM $TPROJ --command "$2"; }

wrapper_for() {   # RUN -> wrapper 脚本名（/content/sts2/ 下）；未知返回 1
  case "$1" in
    *=*) echo "${1#*=}" ;;
    w4-c) echo launch_c2.sh ;; w9-e) echo launch_e.sh ;;
    w4-d) echo launch_d2.sh ;; w9-f) echo launch_f.sh ;;
    *) return 1 ;;
  esac
}
expand_runs() {   # LINE RUNS -> 空格分隔的 chain（v1 单 run 行展开为 v1 隐含的 chain）
  case "$2" in
    *,*) echo "$2" | tr ',' ' ' ;;
    w3m-a) [ "$1" = a ] && echo "w3m-a w4-c w9-e" || echo "$2" ;;
    w3m-b) [ "$1" = b ] && echo "w3m-b w4-d w9-f" || echo "$2" ;;
    *) echo "$2" ;;
  esac
}
ensure_host() {   # NEW OLD：ssh_config 里没有 colab-NEW 时，复制 colab-OLD（或第一个 colab-*）的块并改名
  local N=$1 O=$2 tpl
  grep -q "^Host colab-$N\$" "$SSHCFG" && return 0
  tpl=$(awk -v h="Host colab-$O" '$0==h{p=1;print;next} /^Host /{p=0} p' "$SSHCFG")
  [ -n "$tpl" ] || tpl=$(awk '/^Host colab-/{if(n++)exit} n' "$SSHCFG")
  [ -n "$tpl" ] || { log "no colab-* Host block in $SSHCFG to copy for $N"; return 1; }
  printf '\n%s\n' "$(echo "$tpl" | sed -E "s/^Host colab-[^ ]+\$/Host colab-$N/; s/-s [^ ]+\$/-s $N/")" >> "$SSHCFG"
  log "added Host colab-$N to $SSHCFG"
}
gen_restore() {   # OUTFILE LINE "RUN:WRAPPER ..." RUN... -> VM 上的恢复脚本（不含任何密钥内容，只有路径）
  local f=$1 L=$2 wraps="" w; for w in $3; do wraps="$wraps ${w#*:}"; done; shift 3
  cat > "$f" <<EOF
#!/bin/bash
# restore_chain.sh — generated by watch_rotate.sh $(date -u +%FT%TZ): line $L, runs $*
# 末行标记：RESTORE-OK CK0=<ckpt> 或 RESTORE-FAIL <原因>
set -u
cd /content/sts2 || { echo "RESTORE-FAIL no /content/sts2"; exit 1; }
K=/content/sts2/gcs-sts2-ckpt.json; B=$BUCKET
echo "\$(date -u '+%F %T') unpack stage + bundles"
tar xzf /content/stage.tgz 2>/dev/null || { echo "RESTORE-FAIL unpack stage.tgz"; exit 1; }
[ -f /content/gcs-sts2-ckpt.json ] && mv /content/gcs-sts2-ckpt.json \$K; chmod 600 \$K
for f in sts2train-*.tar.gz; do tar xzf "\$f" 2>/dev/null || { echo "RESTORE-FAIL unpack \$f"; exit 1; }; done
pull() {   # 空 prefix（phase 未开始）时 gcs_pull 恢复 0 个文件、rc 0，run dir 可能不存在
  timeout -k 10 1800 python3 /content/sts2/gcs_pull.py --key \$K --bucket \$B --prefix runs/\$1 --dest /content/sts2/runs/\$1 \\
    --newest-ckpt-only --skip-existing > /content/sts2/runs/.pull-\$1.log 2>&1; local rc=\$?
  echo "pull \$1 rc \$rc: \$(tail -1 /content/sts2/runs/.pull-\$1.log)"; return \$rc
}
small_ok() { ( cd /content/sts2/runs/\$1 2>/dev/null && [ -s status.json ] && [ -s metrics.jsonl ] && [ -s evals.jsonl ] ); }
mkdir -p /content/sts2/runs
for r in $*; do
  pull \$r || { echo "pull of \$r failed: retrying once"; pull \$r || { echo "RESTORE-FAIL gcs_pull \$r"; exit 1; }; }
  if [ -d runs/\$r/checkpoints ]; then
    # 小日志必须在 trainer 追加之前回来，否则 gcs_sync 会覆盖 bucket 里的历史（2026-11-05 事故）
    if ! small_ok \$r; then
      echo "small logs missing for \$r: re-pulling"; pull \$r
      small_ok \$r || { echo "restore of \$r incomplete"; echo "RESTORE-FAIL incomplete \$r"; exit 1; }
    fi
    echo "ok \$r: newest \$(ls runs/\$r/checkpoints | grep '^ckpt-' | sort | tail -1), pinned \$(ls runs/\$r/checkpoints | grep -c '^pinned-')"
  else
    echo "ok \$r: no checkpoints in the bucket yet (phase not started)"
  fi
done
# wrapper 直接引用的本地 fork checkpoint 必须在（line b：launch_d2.sh / launch_f.sh 用 runs/w3m-b/checkpoints/pinned-0007664.pt；
# --newest-ckpt-only 只过滤 ckpt-*.pt，pinned-*.pt 全部恢复，所以恢复 RUNS[0]=w3m-b 后它应该在）
for w in$wraps; do
  for p in \$(grep -oh '/content/sts2/runs/[A-Za-z0-9_.-]*/checkpoints/pinned-[0-9]*\.pt' /content/sts2/\$w 2>/dev/null | sort -u); do
    [ -s "\$p" ] || { echo "RESTORE-FAIL fork checkpoint \$p (used by \$w) missing"; exit 1; }
  done
done
CK0=\$(ls runs/$1/checkpoints 2>/dev/null | grep '^ckpt-' | sort | tail -1)
[ -n "\$CK0" ] || { echo "RESTORE-FAIL no ckpt-*.pt restored for $1"; exit 1; }
echo "\$(date -u '+%F %T') RESTORE-OK CK0=\$CK0"
EOF
}

rotate() {   # OLD LINE RUNS_STR NEW LIVE -> 0 ok；1 暂时失败（下个 tick 重试）；2 需人工（表行改为 #HOLD）
  local OLD=$1 L=$2 RSTR=$3 NEW=$4 LIVE=$5 t0=$SECONDS
  local RUNS R0 r w CK out mk i wraps="" lastlog rc
  RUNS=$(expand_runs "$L" "$RSTR"); set -- $RUNS; R0=${1%%=*}; local PLAIN=$R0
  lastlog=/content/sts2/runs/$R0.driver.log
  for r in "${@:2}"; do
    w=$(wrapper_for "$r") || { log "no wrapper known for run $r of line $L"; alert "rotation of $OLD blocked: no wrapper for run $r"; return 2; }
    wraps="$wraps ${r%%=*}:$w"; PLAIN="$PLAIN ${r%%=*}"; lastlog=/content/sts2/runs/${r%%=*}.driver.log
  done
  RUNS=$PLAIN
  log "ROTATE $OLD -> $NEW (line $L, chain $RUNS)"
  ensure_host "$NEW" "$OLD" || return 1
  if echo "$LIVE" | grep "^\[$NEW\]" | grep -q "Hardware" && ! echo "$LIVE" | grep "^\[$NEW\]" | grep -q "Hardware: CPU"; then
    log "$NEW already exists as a GPU runtime (earlier attempt): reusing it"
  else
    if echo "$LIVE" | grep "^\[$NEW\]" | grep -q "Hardware: CPU"; then
      log "$NEW exists as a CPU ghost runtime: stopping it before colab new"
      x 180 colab --auth=adc stop -s "$NEW" >> "$D/watch.log" 2>&1
    fi
    for ((i = 0; i < 240; i++)); do
      out=$(x 400 colab --auth=adc new --gpu A100 -s "$NEW" 2>&1 | grep -v "gcloud auth\|--scopes" | tail -2 | tr '\n' ' ')
      log "new $NEW: ${out:0:160}"
      echo "$out" | grep -q "READY" && break
      (( SECONDS - t0 > 14400 )) && break
      nap 60
    done
    echo "$out" | grep -q "READY" || { log "giving up on $NEW after 4 h"; return 1; }
  fi
  mkdir -p "$D/.gen/$NEW"; gen_restore "$D/.gen/$NEW/restore_chain.sh" "$L" "$wraps" $RUNS
  x 900 scp -q -F "$SSHCFG" "$D/stage.tgz" "$KEY" "$D/.gen/$NEW/restore_chain.sh" "colab-$NEW:/content/" || { log "scp to $NEW failed"; return 1; }
  # 恢复在 VM 上脱离 ssh 运行：ssh 被掐不会杀掉恢复。
  # 先查 NEW 上是否已有 driver/wrapper 在跑（复用的 NEW 上 chain 已起过、只是表没更新）：有就不恢复、不重起，hold 该行，
  # 防止同一 run dir 上出现两个 trainer。pgrep 的模式写成 [.]，命令文本自身不会被匹配。
  out=$(vm 120 "$NEW" "if pgrep -f 'launch_[a-z0-9]*[.]sh|w3m_line[.]sh' > /dev/null; then echo CHAIN-ALREADY-RUNNING; else mkdir -p /content/sts2/runs && mv /content/restore_chain.sh /content/sts2/ && cd /content/sts2 && setsid nohup bash /content/sts2/restore_chain.sh > /content/sts2/restore.log 2>&1 < /dev/null & disown; echo restore started; fi" 2>&1); rc=$?
  echo "$out" >> "$D/watch.log"
  if echo "$out" | grep -q CHAIN-ALREADY-RUNNING; then
    log "$NEW already runs a driver/wrapper: NOT restoring or starting again"
    alert "rotation $OLD -> $NEW: chain processes already running on $NEW; NOT restarted (line $L held; check $NEW and the keepalive by hand)"
    return 2
  fi
  [ $rc = 0 ] && echo "$out" | grep -q "restore started" || { log "starting the restore on $NEW failed"; return 1; }
  mk=""
  for ((i = 0; i < RESTORE_MAX_S / 30; i++)); do
    nap 30
    out=$(vm 60 "$NEW" "tail -4 /content/sts2/restore.log" 2>/dev/null)
    mk=$(echo "$out" | grep -E "RESTORE-(OK|FAIL)" | tail -1)
    [ -n "$mk" ] && break
  done
  echo "$out" | sed 's/^/  restore| /' >> "$D/watch.log"
  case "$mk" in
    *RESTORE-OK*) CK=$(echo "$mk" | sed -n 's/.*CK0=\([^ ]*\).*/\1/p') ;;
    *"RESTORE-FAIL incomplete"*) r=${mk##* }; log "restore of $r incomplete: NOT starting"; alert "restore of $r on $NEW incomplete: NOT starting (line $L held; $NEW is up and billing)"; return 2 ;;
    *RESTORE-FAIL*) log "restore on $NEW failed: $mk: NOT starting"; alert "restore on $NEW failed ($mk): NOT starting (line $L held; $NEW is up and billing)"; return 2 ;;
    # 超时不重试：VM 上的恢复可能还在跑，下个 tick 重新 scp + 再起一个恢复会和它并发写同一 run dir
    *) log "no restore marker from $NEW after $RESTORE_MAX_S s: NOT starting"; alert "restore on $NEW timed out after $RESTORE_MAX_S s: NOT starting (line $L held; $NEW is up and billing; see /content/sts2/restore.log)"; return 2 ;;
  esac
  [ -n "$CK" ] || { log "no checkpoint name for $R0"; return 1; }
  # 一条 ssh 启动整条 chain：RUNS[0] 的 driver（与 v1 相同的命令行），再按顺序起每个 wrapper
  local cmd="cd /content/sts2 && WAIT_MAX_S=3600 setsid nohup bash /content/sts2/w3m-src/scripts/colab/w3m_line.sh $BUNDLE0 /content/sts2/runs/$R0 $L /content/sts2/runs/$R0/checkpoints/$CK off >> /content/sts2/runs/$R0.driver.log 2>&1 < /dev/null & disown"
  for w in $wraps; do
    cmd="$cmd; sleep 2; setsid nohup bash /content/sts2/${w#*:} >> /content/sts2/runs/${w%%:*}.driver.log 2>&1 < /dev/null & disown"
  done
  cmd="$cmd; sleep 5; echo chain started"
  vm 120 "$NEW" "$cmd" >> "$D/watch.log" 2>&1
  # 进程数用一条单独的短 ssh 数：在启动命令里数会把该 ssh 自己的 bash -c（命令文本含 w3m_line.sh / launch_*.sh）也算进去
  local cnt nw got
  cnt=$(vm 60 "$NEW" "echo driver \$(pgrep -f 'w3m_line[.]s[h]' | wc -l) wrappers \$(pgrep -f 'launch_[a-z0-9]*[.]s[h]' | wc -l)" 2>/dev/null | tail -1)
  nw=$(( $(echo $wraps | wc -w) )); got=$(echo "$cnt" | sed -n 's/.*wrappers \([0-9][0-9]*\).*/\1/p')
  log "chain on $NEW: ${cnt:-<count ssh failed>} (expect wrappers $nw; the $R0 driver may already have exited with '$R0: done')"
  if [ -z "$got" ] || [ "$got" -lt "$nw" ]; then
    alert "chain start on $NEW unverified (${cnt:-count ssh failed}; expected $nw wrappers): check by hand"
  fi
  # keepalive 改指向：sessions.json 推到 Tokyo；sessions.txt 里 OLD 行整行换成 "NEW <最后一个 wrapper 的日志>"（没有 OLD 行就追加）。
  # 必须看最后一个 wrapper 的日志：中间 wrapper 的日志在该 phase 结束时以 ': done' 收尾，keepalive 会在下一个 phase 开跑前停掉 runtime。
  x 200 gcloud compute scp $TPROJ "$SESS_JSON" "$TVM:~/sts2keep/sessions.json" >> "$D/watch.log" 2>&1 \
    && tokyo 200 "cp ~/sts2keep/sessions.json ~/.config/colab-cli/sessions.json && if grep -q '^$OLD ' ~/sts2keep/sessions.txt; then sed -i 's|^$OLD .*|$NEW $lastlog|' ~/sts2keep/sessions.txt; else echo '$NEW $lastlog' >> ~/sts2keep/sessions.txt; fi; cat ~/sts2keep/sessions.txt" >> "$D/watch.log" 2>&1 \
    || { log "Tokyo keepalive repoint for $NEW failed"; alert "Tokyo keepalive repoint $OLD -> $NEW failed: set '$NEW $lastlog' in ~/sts2keep/sessions.txt by hand"; }
  if grep -q "^$OLD " "$SC/colab/sessions.txt" 2>/dev/null; then sed -i.bak "s|^$OLD .*|$NEW $lastlog|" "$SC/colab/sessions.txt"; else echo "$NEW $lastlog" >> "$SC/colab/sessions.txt"; fi
  log "ROTATED $OLD -> $NEW: chain $RUNS resumed ($R0 from $CK); took $((SECONDS - t0)) s"
  alert "rotated $OLD -> $NEW"
  return 0
}

tick() {
  local live S L RUNS NEXT ka stopped last rc NN
  live=$(x 120 colab --auth=adc sessions 2>&1)
  if ! echo "$live" | grep -q "Hardware"; then log "colab sessions failed: ${live:0:120}"; return; fi
  while read -r S L RUNS NEXT; do
    [ -z "$S" ] && continue
    case "$S" in \#*) continue ;; esac
    if echo "$live" | grep "^\[$S\]" | grep -q "Hardware: CPU"; then
      log "$S exists but is a CPU runtime (auto-created by a proxy connection): stopping it and treating as missing"
      x 180 colab --auth=adc stop -s "$S" >> "$D/watch.log" 2>&1
      live=$(echo "$live" | grep -v "^\[$S\]")
    fi
    echo "$live" | grep -q "^\[$S\]" && continue
    # 一次 gcloud ssh，两段输出：keepalive 是否停过 S，以及 S 的最后一条 'ping ok' 行
    ka=$(tokyo 200 "echo STOPPED=\$(grep -c '$S driver done -> stopping' ~/sts2keep/keepalive.log); echo LAST=\$(grep ' $S ping ok' ~/sts2keep/keepalive.log | tail -1)" 2>/dev/null)
    stopped=$(echo "$ka" | sed -n 's/^STOPPED=//p' | tail -1)
    last=$(echo "$ka" | sed -n 's/^LAST=//p' | tail -1)
    if [ -z "$stopped" ]; then log "$S missing but the Tokyo keepalive query failed: skipping this tick"; continue; fi
    if [ "$stopped" != 0 ]; then
      if [ -z "$last" ] || echo "$last" | grep -qE 'abnormally|exited rc|giving up|failed|: stop'; then
        log "FAILURE on $S: ${last:-<no ping line>}"; alert "FAILURE on $S: ${last:-<no ping line>}"
      else
        log "$S finished on purpose ($last)"
      fi
      sed -i.bak -E "/^$S[[:space:]]/d" "$D/managed.txt"; continue
    fi
    log "$S missing from colab sessions -> rotating"
    rotate "$S" "$L" "$RUNS" "$NEXT" "$live"; rc=$?
    if [ $rc = 0 ]; then
      case "$NEXT" in *2) NN=${NEXT%2}3 ;; *3) NN=${NEXT%3}4 ;; *) NN=${NEXT}2 ;; esac
      # 按行首 session 名整行替换（对多余空白不敏感）；没改成功就告警，否则下个 tick 会对已在跑的 NEXT 再轮换一次
      sed -i.bak -E "s/^$S[[:space:]].*/$NEXT $L $RUNS $NN/" "$D/managed.txt"
      grep -q "^$NEXT $L $RUNS $NN\$" "$D/managed.txt" || alert "managed.txt not updated after rotating $S -> $NEXT: fix the table by hand"
    elif [ $rc = 2 ]; then
      log "rotation of $S needs a human: holding the table line"
      sed -i.bak -E "s/^$S[[:space:]].*/#HOLD $S $L $RUNS $NEXT/" "$D/managed.txt"
    else
      log "rotation of $S FAILED; will retry next tick"
    fi
  done < "$D/managed.txt"
}

while [ -f "$D/RUN" ]; do
  tick
  [ "${ONE_TICK:-0}" = 1 ] && break
  nap "$I"
done
