"""Boss-HP fraction of an episode that ended inside an act-boss fight (wave 20; ``--boss-hp-bonus``).

Why: every death in a boss room scores the same protocol progress (0.958 in the act-3 boss room at A10), so the trainer
gets no signal for how much boss HP a fight removed (``docs/diag-2026-11-06/final-boss-losses.md``). This module
measures it from the observations the episode decided at; ``objective.EpisodeRewards`` records it on every boss-death
episode (``boss_death_hp_frac``, always on) and pays ``--boss-hp-bonus B`` x it at the terminal step (B != 0).

**Encounter table** (``boss_hp.json`` next to this file, generated by ``python -m sts2train.bosshp --write`` from
``sim/specs/inventory/{encounters,monsters}.json``, the sim's ``Monsters/Encounters/*Boss.cs`` (spawn lists) and
``Monsters/Defs/*.cs`` (``Apply<MinionPower>`` = minion; ``TestSubject.cs`` form HP constants); ``tests/test_boss_hp.py``
regenerates it and compares). Per boss encounter: the **required units** (monsters that must die; minions such as
QUEEN's TORCH_HEAD_AMALGAM or THE_KIN's KIN_FOLLOWERs are left out: they die with their leader) with their **forms**
(HP of each life of one creature: TEST_SUBJECT revives in place, same uid, as 111 / 212 / 313 at ToughEnemies; every
other boss unit has one form), at ``base`` (ascension < 8) and ``tough`` (ascension >= 8 = ``AscensionLevel.ToughEnemies``)
levels, and the **pool** = the sum of the forms of the required units (A8+: AEONGLASS 535, QUEEN 419, TEST_SUBJECT 636,
KAISER_CRAB 428 = CRUSHER 219 + ROCKET 209, ...). The level is read per slot from ``global_i.ascension`` (a save keeps
its own ascension). The observation alone cannot give the total (TEST_SUBJECT's first decision shows max_hp 111 only).

**One boss fight.** A slot is in an act-boss fight when ``global_i.is_combat`` > 0 and the current map node
(``map_nodes[map_row, map_col].point_type``) is ``Boss`` (``sts2vec.runstats``); which of the act's bosses it is: the
second (``second_boss_id``) when ``map_routes[row, col].boss_dist != 0`` (-1 at the second boss of a double-boss act),
else the first (``boss_id``). A new fight starts when (act, floor, second) changes. Remaining required HP::

    R = sum over required units u of
          hp(row of u) + sum(forms_u after the current form)     if u's row is present (current form = the form whose
                                                                 HP equals the row's max_hp; unchanged when none does)
          sum(forms_u after the last seen form)                  if u was seen and its row is absent (dead, or
                                                                 TEST_SUBJECT waiting to revive: 0 after its last form)
          sum(forms_u)                                           if u was never seen

Rows are tied to units by uid (``enemies.uid``), the first time by monster id (``enemies.monster_id`` -> monsters
vocabulary name). ``f = clip((R_first - R_last) / pool, 0, 1)``: R_first at the **first decision of that fight the
episode observed** (the fight entry for fresh, harvest-anchor and save starts: anchors are captured at a combat's first
decision and a save resumes a room from its start; a mid-fight restore measures from the restored state), R_last at the
last decision the episode observed (the one before the step that ended it; with auto-reset the post-step observation
already belongs to the successor).

**Fallback** (an encounter id missing from the table, or no boss id): every enemy row seen in the fight is a unit with
one form = its max_hp at first sight; pool = the sum of those, R_first = the sum of their HP at first sight (later
summons add theirs), R = current HP of present rows (0 once absent). ``encounter`` is then the id's name with
``table: false``.

**Per act** (``boss_death_hp_frac``): ``F = (k + f) / n`` with ``n`` = 2 when the act has a second boss
(``global_i.second_boss_id`` > 0: A10's last act, ``AscensionLevel.DoubleBoss``) else 1, and ``k`` = 1 when the death
fight is the second boss and the episode observed the first boss fight of that act (so it killed it), else 0. F is
monotone over the act's boss fights (dying 90% into boss 1 scores below reaching boss 2), unlike a per-fight f
(``boss_death_fight_frac``). Nothing is measured for a win, a death outside a boss fight, a FloorStall / error end,
or an act below ``min_act``.

Cost per ``observe``: a column gather of ``global_i`` and, for the combat slots, one gather of the current map node;
Python work only for the slots in a boss fight of act >= ``min_act`` (a few per step, <= 6 enemy rows each).
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np

TABLE_PATH = Path(__file__).with_name("boss_hp.json")
TOUGH_ENEMIES = 8                       # AscensionLevel.ToughEnemies (sim/Sts2Sim.Core/Enums/CombatEnums.cs)
_G = ("is_combat", "act_index", "total_floor", "map_row", "map_col", "boss_id", "second_boss_id")
_E = ("present", "uid", "monster_id", "hp", "max_hp")

_TABLE: dict | None = None


def load_table(path: Path | str | None = None) -> dict:
    """The committed encounter table (``boss_hp.json``; cached for the default path)."""
    global _TABLE
    if path is None:
        if _TABLE is None:
            _TABLE = json.loads(TABLE_PATH.read_text())
        return _TABLE
    return json.loads(Path(path).read_text())


# ------------------------------------------------------------------------------------------------ table generation
def _repo_root() -> Path:
    return Path(__file__).resolve().parents[4]          # sim/tools/train/sts2train/bosshp.py -> repo


def build_table(root: Path | str | None = None) -> dict:
    """Regenerate the encounter table from the repo's inventory and sim sources (module docstring). Raises when the
    sources disagree (an encounter's spawn list vs the inventory, a unit without a fixed HP)."""
    root = Path(root) if root is not None else _repo_root()
    inv = root / "sim" / "specs" / "inventory"
    core = root / "sim" / "Sts2Sim.Core" / "Monsters"
    encs = json.loads((inv / "encounters.json").read_text())["entries"]
    mons = json.loads((inv / "monsters.json").read_text())["entries"]
    by_class = {m["class"]: m for m in mons}
    minion_classes = sorted(p.stem for p in (core / "Defs").glob("*.cs") if "Apply<MinionPower>" in p.read_text())
    minions = {by_class[c]["id"] for c in minion_classes if c in by_class}
    ts = (core / "Defs" / "TestSubject.cs").read_text()

    def const(name: str) -> int:
        m = re.search(rf"const int {name} = (\d+);", ts)
        if not m:
            raise ValueError(f"TestSubject.cs: no constant {name}")
        return int(m.group(1))

    forms_override = {"TEST_SUBJECT": {"base": [const(f"{k}FormHpBase") for k in ("First", "Second", "Third")],
                                       "tough": [const(f"{k}FormHpTough") for k in ("First", "Second", "Third")]}}
    out: dict = {}
    for e in sorted((x for x in encs if x.get("room_kind") == "boss" and x.get("act_index") is not None),
                    key=lambda x: x["id"]):
        src = (core / "Encounters" / f"{e['class']}.cs").read_text()
        body = src[src.index("GenerateMonsters"):]
        spawned = re.findall(r'MonsterRegistry\.Get\("([A-Z0-9_]+)"\)', body)
        inv_ids = sorted({by_class[c]["id"] for c in e["monsters_in_generate"]})
        if sorted(set(spawned)) != inv_ids:
            raise ValueError(f"{e['id']}: sim spawns {sorted(set(spawned))}, the inventory lists {inv_ids}")
        units = []
        for mid in spawned:
            if mid in minions:
                continue
            if mid in forms_override:
                forms = forms_override[mid]
            else:
                m = next(x for x in mons if x["id"] == mid)
                lo, hi = m.get("min_hp"), m.get("max_hp")
                if not lo or not hi or lo["a0"] != hi["a0"] or lo["ascended"] != hi["ascended"] \
                        or lo.get("level") != "ToughEnemies":
                    raise ValueError(f"{e['id']}: {mid} has no fixed HP in the inventory ({lo} / {hi})")
                forms = {"base": [int(lo["a0"])], "tough": [int(lo["ascended"])]}
            units.append({"monster": mid, "forms": forms})
        out[e["id"]] = {"act": int(e["act_index"]) + 1, "units": units,
                        "minions": sorted({m for m in spawned if m in minions}),
                        "pool": {lv: sum(sum(u["forms"][lv]) for u in units) for lv in ("base", "tough")}}
    return {"_doc": "Boss encounter HP table for sts2train.bosshp (wave 20). Generated: do not edit; regenerate with "
                    "`uv run python -m sts2train.bosshp --write` in sim/tools/train.",
            "sources": ["sim/specs/inventory/encounters.json", "sim/specs/inventory/monsters.json",
                        "sim/Sts2Sim.Core/Monsters/Encounters/*Boss.cs", "sim/Sts2Sim.Core/Monsters/Defs/*.cs"],
            "tough_enemies_ascension": TOUGH_ENEMIES, "minion_classes": minion_classes, "encounters": out}


def dump_table(table: dict) -> str:
    return json.dumps(table, indent=1, sort_keys=True) + "\n"


# ------------------------------------------------------------------------------------------------ one fight
class Fight:
    """Remaining-HP bookkeeping of one boss fight of one slot (module docstring). ``units`` None = fallback mode."""

    __slots__ = ("encounter", "in_table", "units", "uid_unit", "pool", "r_first", "r_last", "fb_first")

    def __init__(self, encounter: str | None, entry: dict | None, tough: bool):
        self.encounter = encounter
        self.in_table = entry is not None
        lv = "tough" if tough else "base"
        # unit: [monster, forms, uid, form index, hp, seen, present]
        self.units = None if entry is None else [[u["monster"], list(u["forms"][lv]), None, 0, 0, False, False]
                                                 for u in entry["units"]]
        self.uid_unit: dict[int, list] = {}
        self.pool = float(entry["pool"][lv]) if entry is not None else 0.0
        self.r_first: float | None = None
        self.r_last = 0.0
        self.fb_first = 0.0             # fallback: summed HP at first sight

    def update(self, rows) -> float:
        """Feed one decision's enemy rows (iterable of (uid, monster name, hp, max_hp) of the present rows); returns
        and stores R (the remaining required HP)."""
        if self.units is None:
            return self._update_fallback(rows)
        for u in self.units:
            u[6] = False
        for uid, name, hp, mx in rows:
            u = self.uid_unit.get(uid)
            if u is None:
                u = next((x for x in self.units if x[2] is None and x[0] == name), None)
                if u is None:
                    continue                        # a minion / summon outside the required set
                u[2] = uid
                self.uid_unit[uid] = u
            forms = u[1]
            if mx in forms:
                u[3] = forms.index(mx)
            u[4], u[5], u[6] = max(int(hp), 0), True, True
        r = 0.0
        for _, forms, _, k, hp, seen, present in self.units:
            if present:
                r += hp + sum(forms[k + 1:])
            elif seen:
                r += sum(forms[k + 1:])
            else:
                r += sum(forms)
        return self._set(r)

    def _update_fallback(self, rows) -> float:
        r = 0.0
        for uid, name, hp, mx in rows:
            if uid not in self.uid_unit:
                self.uid_unit[uid] = [name]
                self.pool += max(int(mx), 0)
                self.fb_first += max(int(hp), 0)
            r += max(int(hp), 0)
        self.r_first = self.fb_first            # later summons add their first-sight HP to the baseline
        self.r_last = r
        return r

    def _set(self, r: float) -> float:
        if self.r_first is None:
            self.r_first = r
        self.r_last = r
        return r

    def frac(self) -> float:
        if self.pool <= 0 or self.r_first is None:
            return 0.0
        return float(min(1.0, max(0.0, (self.r_first - self.r_last) / self.pool)))


# ------------------------------------------------------------------------------------------------ per slot
class BossHpTracker:
    """Per-slot boss-fight state from the observations the slots decide at.

    ``observe(obs)`` with every observation the slots will decide at (``env.reset()``'s and each ``env.step``'s, after
    ``end`` / ``clear`` of the slots whose episode ended in that step); ``end(slot)`` -> the measurement of the episode
    that just ended on `slot` from its last decision (None when that decision was not in a boss fight of act >=
    ``min_act``); ``clear(mask)`` resets the per-episode state of the slots (their successors start empty)."""

    def __init__(self, schema, num_envs: int, *, ascension: int = 0, min_act: int = 2, table: dict | None = None):
        self.n = int(num_envs)
        self.min_act = int(min_act)
        self.ascension = int(ascension)
        tab = table if table is not None else load_table()
        self.table = tab["encounters"]
        self.tough_level = int(tab.get("tough_enemies_ascension", TOUGH_ENEMIES))
        has = set(schema.names)
        missing = [b for b in ("global_i", "enemies", "map_nodes") if b not in has]
        G = schema.cols("global_i") if "global_i" in has else {}
        E = schema.cols("enemies") if "enemies" in has else {}
        missing += [f"global_i.{k}" for k in _G if k not in G] + [f"enemies.{k}" for k in _E if k not in E]
        pt_names = list(schema.vocab.enums.get("MapPointType") or [])
        if "Boss" not in pt_names:
            missing.append("enum MapPointType.Boss")
        self.missing = missing
        self.ok = not missing
        if not self.ok:
            return
        self._g = {k: G[k] for k in _G}
        self._asc = G.get("ascension", -1)
        self._e = tuple(E[k] for k in _E)
        self._pt = schema.cols("map_nodes")["point_type"]
        self._map_shape = tuple(schema["map_nodes"].shape[:2])
        self._bd = schema.cols("map_routes").get("boss_dist", -1) if "map_routes" in has else -1
        self._boss_pt = pt_names.index("Boss")
        lists = schema.vocab.lists
        self.enc_name = lists["encounters"].name if "encounters" in lists else (lambda i: f"<{int(i)}>")
        self.mon_name = lists["monsters"].name if "monsters" in lists else (lambda i: f"<{int(i)}>")
        self.in_fight = np.zeros(self.n, dtype=bool)        # the slot's last decision was in a tracked boss fight
        self.key = np.full((self.n, 3), -1, dtype=np.int64)  # (act_index, total_floor, second) of the slot's fight
        self.double = np.zeros(self.n, dtype=bool)          # that act has a second boss (second_boss_id > 0)
        self.first_act = np.full(self.n, -1, dtype=np.int64)  # act_index of the last first-boss fight observed
        self.fights: list[Fight | None] = [None] * self.n

    def clear(self, mask=None) -> None:
        if not self.ok:
            return
        idx = np.arange(self.n) if mask is None else np.flatnonzero(np.asarray(mask, dtype=bool))
        self.in_fight[idx] = False
        self.key[idx] = -1
        self.double[idx] = False
        self.first_act[idx] = -1
        for s in idx.tolist():
            self.fights[s] = None

    def observe(self, obs: dict) -> None:
        if not self.ok:
            return
        gi = obs["global_i"]
        g = self._g
        act = gi[:, g["act_index"]]
        cand = np.flatnonzero((gi[:, g["is_combat"]] > 0) & (act + 1 >= self.min_act))
        self.in_fight[:] = False
        if len(cand) == 0:
            return
        r = gi[cand, g["map_row"]].astype(np.int64)
        c = gi[cand, g["map_col"]].astype(np.int64)
        R, C = self._map_shape
        ok = (r >= 0) & (r < R) & (c >= 0) & (c < C)
        r, c = np.clip(r, 0, R - 1), np.clip(c, 0, C - 1)
        pt = np.where(ok, obs["map_nodes"][cand, r, c, self._pt], 0)
        boss = ok & (pt == self._boss_pt)
        if not boss.any():
            return
        routes = obs.get("map_routes") if self._bd >= 0 else None
        ep, eu, em, eh, ex = self._e
        for k in np.flatnonzero(boss).tolist():
            s = int(cand[k])
            row = gi[s]
            a, floor = int(row[g["act_index"]]), int(row[g["total_floor"]])
            if routes is not None:
                second = int(routes[s, int(r[k]), int(c[k]), self._bd]) != 0
            elif int(self.key[s, 0]) == a and int(self.key[s, 1]) == floor:
                second = bool(self.key[s, 2])   # no routing buffer: the same fight keeps its kind
            else:                               # ... a new boss fight is the second one after a first one in the act
                second = int(self.first_act[s]) == a
            if (int(self.key[s, 0]), int(self.key[s, 1]), int(self.key[s, 2])) != (a, floor, int(second)):
                bid = int(row[g["second_boss_id"] if second else g["boss_id"]])
                name = self.enc_name(bid) if bid > 0 else None
                asc = int(row[self._asc]) if self._asc >= 0 else self.ascension
                self.fights[s] = Fight(name, self.table.get(name) if name else None, asc >= self.tough_level)
                self.key[s] = (a, floor, int(second))
                self.double[s] = int(row[g["second_boss_id"]]) > 0
                if not second:
                    self.first_act[s] = a
            self.fights[s].update([(x[eu], self.mon_name(x[em]), x[eh], x[ex])
                                   for x in obs["enemies"][s].tolist() if x[ep] > 0])
            self.in_fight[s] = True

    def end(self, slot: int) -> dict | None:
        """The boss-HP measurement of the episode that just ended on `slot` (call before ``clear`` / ``observe``)."""
        if not self.ok:
            return None
        s = int(slot)
        f = self.fights[s]
        if not self.in_fight[s] or f is None:
            return None
        a, _, second = (int(x) for x in self.key[s])
        n = 2 if self.double[s] else 1
        k = 1 if second and n == 2 and int(self.first_act[s]) == a else 0
        fr = f.frac()
        return {"act": a + 1, "encounter": f.encounter, "table": f.in_table, "second": bool(second), "bosses": n,
                "first_killed": k, "fight_frac": fr, "frac": (k + fr) / n, "hp_first": f.r_first,
                "hp_last": f.r_last, "pool": f.pool}


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="python -m sts2train.bosshp",
                                description="Regenerate / check sts2train/boss_hp.json from the repo's sources")
    p.add_argument("--root", help="repo root (default: this checkout)")
    p.add_argument("--write", action="store_true", help="write boss_hp.json (default: check only)")
    a = p.parse_args(argv)
    text = dump_table(build_table(a.root))
    if a.write:
        TABLE_PATH.write_text(text)
        print(f"wrote {TABLE_PATH}")
        return 0
    same = TABLE_PATH.exists() and TABLE_PATH.read_text() == text
    print("boss_hp.json is up to date" if same else "boss_hp.json differs from the sources: run with --write")
    return 0 if same else 1


if __name__ == "__main__":
    raise SystemExit(main())
