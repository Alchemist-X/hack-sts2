"""Requirement catalogue: the feature keys and the rules that map W0 free-text requirements onto keys.

Key forms (requirements.json documents every key):
  <Cmd>.<Method>            kernel-gaps.json cmd_facades[<Cmd>] row(s) named <Method>
  <Cmd>.<Method>(<variant>) one overload family of that facade (the variants content_readiness reports)
  <Hook>                    kernel-gaps.json hook_virtuals row (an AbstractModel hook virtual)
  <Base>.<Virtual>          kernel-gaps.json model_kind_virtuals[<Base>] row
  <area>:<id>               a feature without such a row; `rows` joins it to kernel-gaps.json subsystems /
                            listener_order / prompt_types, run-layer-gaps.json subsystems or subsystems.json

Levels follow the shared tier legend: 1 exists in the P0 sim or has no single-player effect, 2 a game
facade / hook / parameter / model API the P0 sim lacks, 3 a player prompt or a new subsystem, 4 a
decompile loss or cross-cutting work. KIND_BASELINES lists the keys every model of a kind needs (the
kind's own runtime); they count as level 1 for that kind.
"""

