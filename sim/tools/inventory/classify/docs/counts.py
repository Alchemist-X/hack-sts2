"""Normalised counts for the inventory docs (docs/sim-port/inventory-*.md).

Reads the published manifests in --out and writes, per classified file, a generated block between the markers
below into its companion doc (inserted before the doc's first `## ` heading on the first run, replaced after),
plus the whole of docs/sim-port/inventory-minor-kinds.md for the six kinds that have no hand-written doc.
The docs are written into the repo only when --out is the repo's sim/specs/inventory; otherwise into
<work>/docs (so a scratch run never touches docs/).
"""

import collections
import json
import os
import sys
from collections import OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import common  # noqa: E402

BEGIN = "<!-- normalised-counts: generated by sim/tools/inventory/classify/docs/counts.py; do not edit by hand -->"
END = "<!-- /normalised-counts -->"
DOCS = OrderedDict([
    ("cards-ironclad-colorless", "inventory-cards-ironclad-colorless.md"),
    ("cards-necrobinder-regent", "inventory-cards-necrobinder-regent.md"),
    ("cards-silent-defect", "inventory-cards-silent-defect.md"),
    ("powers", "inventory-powers.md"),
    ("relics", "inventory-relics.md"),
    ("potions", "inventory-potions.md"),
    ("monsters", "inventory-monsters.md"),
    ("encounters", "inventory-encounters.md"),
    ("events", "inventory-events.md"),
])
MINOR = ["enchantments", "afflictions", "orbs", "modifiers", "acts", "characters"]
MINOR_DOC = "inventory-minor-kinds.md"
LEGENDS = ("port_batch_legend", "batch_titles", "batch_legend", "port_batch_definition")
CARD_FILES = ("cards-ironclad-colorless", "cards-necrobinder-regent", "cards-silent-defect")


def load(name):
    return common.load_json(os.path.join(common.OUT, name))


def counter_row(c, keys):
    return " | ".join(str(c.get(k, 0)) for k in keys)


def batch_key(b):
    return (0, int(b)) if str(b).isdigit() else (1, str(b))


def legend_title(env, b):
    for k in LEGENDS:
        leg = env.get(k)
        if isinstance(leg, dict) and str(b) in leg:
            v = leg[str(b)]
            return v if isinstance(v, str) else (v.get("title") or json.dumps(v))[:160]
    return ""


def vd_rows(vd, fname, kind):
    rows = [e for e in vd["entries"] if (e.get("classifier") or {}).get("file") == fname + ".classified.json"]
    if fname not in CARD_FILES:
        rows += [e for e in vd["entries"] if e["kind"] == kind and e.get("classifier") is None]
    return rows


def block(fname, env, req, vd, standalone=False):
    ents = env["entries"]
    kind = env["content_kind"]
    tiers = (1, 2, 3, 4)
    t_own = collections.Counter(e["tier"] for e in ents)
    t_dep = collections.Counter(e["tier_with_deps"] for e in ents)
    t_cls = collections.Counter(e.get("tier_classifier") for e in ents)
    changed = [e for e in ents if e.get("tier_classifier") is not None and e["tier"] != e["tier_classifier"]]
    reasons = collections.Counter()
    for e in changed:
        for r in e.get("tier_adjustments") or []:
            reasons[r.split(" (")[0]] += 1
    out = [BEGIN, "", "## Normalised counts (schema v2)", ""]
    w0_tier = {"cards-silent-defect": "their `tier` is the W0 with-dependencies tier and their `tier_own` is `tier_classifier`",
               "encounters": "their tier is `tier_classifier` (W0: the max over the spawned monsters)"}.get(fname, "their tier is `tier_classifier`")
    head = ("`sim/specs/inventory/%s.classified.json` after `classify/normalize/normalize.py` (fields: its `schema_fields`; "
            "tiers 1-4 as in its `tier_legend`)." % fname)
    if not standalone:
        head += " The hand-written sections of this doc are the W0 classification: %s%s." % (
            w0_tier, ", their batch numbers are `port_batch_legacy`" if fname in CARD_FILES else "")
    out.append(head)
    out.append("")
    out.append("| %d entries | tier 1 | tier 2 | tier 3 | tier 4 |" % len(ents))
    out.append("| --- | --- | --- | --- | --- |")
    out.append("| `tier` (own code) | %s |" % counter_row(t_own, tiers))
    out.append("| `tier_with_deps` | %s |" % counter_row(t_dep, tiers))
    if any(k is not None for k in t_cls):
        out.append("| `tier_classifier` (W0) | %s |" % counter_row(t_cls, tiers))
    out.append("")
    if changed:
        out.append("`tier` differs from `tier_classifier` in %d entries: %s." % (
            len(changed), "; ".join("%s %d" % (r, n) for r, n in sorted(reasons.items(), key=lambda x: (-x[1], x[0])))))
        out.append("")
    batches = collections.Counter(str(e.get("port_batch")) for e in ents)
    out.append("| `port_batch` | entries | meaning |")
    out.append("| --- | --- | --- |")
    for b in sorted(batches, key=batch_key):
        out.append("| %s | %d | %s |" % (b, batches[b], legend_title(env, b).replace("|", "/") if b != "None" else "not ported (mock or deprecated)"))
    out.append("")
    if fname in CARD_FILES:
        moved = sum(1 for e in ents if str(e.get("port_batch")) != str(e.get("port_batch_legacy")))
        raised = sum(1 for e in ents if e.get("card_batch_raised_by"))
        out.append("Unified card scheme (`port_batch_legend`, prerequisites `port_batch_prerequisites`, cross-kind order "
                   "`batches.json`): %d entries renumbered from `port_batch_legacy`, %d of them raised by a required power or "
                   "token." % (moved, raised))
        out.append("")
    prompts = [p for e in ents for p in e.get("prompts") or []]
    own = [p for p in prompts if not p.get("via")]
    pk = collections.Counter(p["kind"] for p in prompts)
    phases = collections.Counter(ph["phase"] for e in ents for ph in e.get("phases") or [])
    out.append("Prompts: %d records (%d own, %d opened by an applied power, spawned monster or offered relic, field `via`)%s. "
               "Phases: %s." % (len(prompts), len(own), len(prompts) - len(own),
                                (": " + ", ".join("%s %d" % (k, n) for k, n in sorted(pk.items()))) if pk else "",
                                ", ".join("%s %d" % (k, n) for k, n in sorted(phases.items())) or "none"))
    out.append("")
    keys = collections.Counter(k for e in ents for k in e.get("kernel_requirements") or [])
    by_kind = collections.Counter(req["keys"][k]["kind"] for k in keys)
    top = ", ".join("`%s` %d" % (k, n) for k, n in sorted(keys.items(), key=lambda x: (-x[1], x[0]))[:8])
    out.append("Requirements: %d distinct catalogue keys of `requirements.json` (%s); most used: %s." % (
        len(keys), ", ".join("%s %d" % (k, n) for k, n in sorted(by_kind.items())), top or "none"))
    out.append("")
    st = collections.Counter((e.get("version_delta_v107") or {}).get("status") for e in ents)
    rows = vd_rows(vd, fname, kind)
    tri = collections.Counter(e["triage"] for e in rows)
    dis = [e["key"] for e in rows if (e.get("classifier") or {}).get("status") == "same" and e.get("sources") != "version_delta"]
    vdk = [e["key"] for e in rows if e.get("sources") == "version_delta"]
    unreach = sum(1 for e in rows if e["triage"] == "changed" and not e.get("single_player_reachable", True))
    def tri_of(k):
        return next(e["triage"] for e in rows if e["key"] == k)
    tail = ("; flagged by the diff gate while the classifier said same: " + ", ".join(
        "%s (%s)" % (k.split(":", 1)[1], tri_of(k)) for k in dis)) if dis else ""
    tail += ("; unique edits found by scripts/version_delta.py that both missed: " + ", ".join(
        "%s (%s)" % (k.split(":", 1)[1], tri_of(k)) for k in vdk)) if vdk else ""
    out.append("Version delta v0.107.1 -> v0.111.0: classifier status %s; `version-deltas.json` triage of the %d entries "
               "listed there: changed %d%s, refactor_only %d, unknown %d%s." % (
                   ", ".join("%s %d" % (k, n) for k, n in sorted(st.items(), key=lambda x: str(x[0]))), len(rows),
                   tri["changed"], (" (%d of them not single-player reachable)" % unreach) if unreach else "",
                   tri["refactor_only"], tri["unknown"], tail))
    out.append("")
    out.append(END)
    return "\n".join(out)


def splice(text, blk):
    if BEGIN in text and END in text:
        a = text.index(BEGIN)
        b = text.index(END) + len(END)
        return text[:a] + blk + text[b:]
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if line.startswith("## "):
            return "\n".join(lines[:i] + blk.split("\n") + [""] + lines[i:])
    return text.rstrip("\n") + "\n\n" + blk + "\n"


def cell(s, n=220):
    s = " ".join(str(s).split()).replace("|", "/")
    return s if len(s) <= n else s[:n - 3] + "..."


def minor_doc(req, vd):
    out = ["# Inventory: enchantments, afflictions, orbs, modifiers, acts, characters", ""]
    out.append("Generated by `sim/tools/inventory/classify/docs/counts.py` from the six `*.classified.json` files of "
               "`sim/specs/inventory/` (W1 critique G1; records in `sim/tools/inventory/classify/minor-kinds/data_<kind>.py`, "
               "each mechanic citing the v0.111.0 decompile). Do not edit by hand.")
    out.append("")
    for kind in MINOR:
        env = load(kind + ".classified.json")
        out.append(block(kind, env, req, vd, standalone=True).replace("## Normalised counts (schema v2)", "## %s" % kind.capitalize())
                   .replace(BEGIN + "\n\n", "").replace("\n\n" + END, ""))
        out.append("")
        out.append("| id | scope | tier | with deps | batch | mechanics | requirements | v0.107.1 |")
        out.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
        for e in env["entries"]:
            vdx = e.get("version_delta_v107") or {}
            out.append("| `%s` | %s | %s | %s | %s | %s | %s | %s |" % (
                e["id"], e.get("scope"), e["tier"], e["tier_with_deps"], e.get("port_batch"),
                cell("; ".join(e.get("mechanics") or [])), cell(", ".join(e.get("kernel_requirements") or []) or "-", 160),
                cell("%s%s" % (vdx.get("status"), (": " + vdx["note"]) if vdx.get("status") not in ("same", None) and vdx.get("note") else ""), 160)))
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    req = load("requirements.json")
    vd = load("version-deltas.json")
    default_out = os.path.join(common.REPO_ROOT, "sim", "specs", "inventory")
    docs = os.path.join(common.REPO_ROOT, "docs", "sim-port") if common.OUT == os.path.abspath(default_out) else common.work_dir("docs")
    for fname, doc in DOCS.items():
        env = load(fname + ".classified.json")
        src = os.path.join(common.REPO_ROOT, "docs", "sim-port", doc)
        with open(src, encoding="utf-8") as fh:
            text = fh.read()
        new = splice(text, block(fname, env, req, vd))
        with open(os.path.join(docs, doc), "w", encoding="utf-8") as fh:
            fh.write(new)
    with open(os.path.join(docs, MINOR_DOC), "w", encoding="utf-8") as fh:
        fh.write(minor_doc(req, vd))
    print("docs written to", docs)


if __name__ == "__main__":
    main()
