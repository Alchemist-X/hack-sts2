#!/usr/bin/env python3
"""Generate sim/Sts2Sim.Vec/EventOptionVars.g.cs: the placeholders of every event option's text, from the game's own
localisation export (knowledge/source/<version>/events.jsonl, English).

    python3 sim/tools/vec/tools/gen_event_option_vars.py           # rewrite the generated file
    python3 sim/tools/vec/tools/gen_event_option_vars.py --check   # exit 1 if it is stale

The Vec encoder's `event_option_values` table (sim/VEC.md) shows the numbers and items an event option's button text
names (`{Gold}`, `{HpLoss}`, `{Relic}`, `{Card1}` ...). Which placeholders an option shows lives only in the
localisation templates, so this script extracts, per option text key ("<EVENT>.pages.<PAGE>.options.<KEY>", the sim's
`EventOption.TextKey`), the placeholder names of the title and then the description in order of first appearance; the
encoder resolves each name on the live event model exactly like the play server's rules text
(`Sts2Sim.Server/RulesText.cs` EventScope). Version directories are read oldest first and a newer version's option
replaces an older one (the server's merge order). Standard library only; tests/test_event_option_vars.py runs --check.
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
SOURCE = REPO / "knowledge" / "source"
OUT = REPO / "sim" / "Sts2Sim.Vec" / "EventOptionVars.g.cs"
PLACEHOLDER = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)")


def _version_key(name: str) -> tuple:
    return tuple(int(x) if x.isdigit() else 0 for x in re.split(r"[.\-]", name.lstrip("v")))


def collect(source: Path = SOURCE) -> tuple[dict[str, list[str]], list[tuple[str, str]]]:
    """(text key -> placeholder names, [(relative path, sha256)] of the files read)."""
    table: dict[str, list[str]] = {}
    files = []
    for vdir in sorted((d for d in source.iterdir() if d.is_dir() and (d / "events.jsonl").exists()),
                       key=lambda d: _version_key(d.name)):
        path = vdir / "events.jsonl"
        data = path.read_bytes()
        files.append((path.relative_to(REPO).as_posix(), hashlib.sha256(data).hexdigest()))
        for line in data.decode("utf-8").splitlines():
            if not line.strip():
                continue
            ev = json.loads(line)
            options = ((ev.get("localized") or {}).get("eng") or {}).get("options") or {}
            for key, opt in options.items():
                names: list[str] = []
                for part in (opt.get("title") or "", opt.get("description") or ""):
                    for m in PLACEHOLDER.finditer(part):
                        if m.group(1) not in names:
                            names.append(m.group(1))
                full = f"{ev['id']}.pages.{key}"
                if names:
                    table[full] = names
                else:
                    table.pop(full, None)
    return dict(sorted(table.items())), files


def render(table: dict[str, list[str]], files: list[tuple[str, str]]) -> str:
    out = ["// <auto-generated>",
           "// Generated by sim/tools/vec/tools/gen_event_option_vars.py from the game's localisation export; do not edit.",
           "// Regenerate: python3 sim/tools/vec/tools/gen_event_option_vars.py (--check in the vec tests).",
           "// </auto-generated>"]
    out += [f"// source: {p} sha256 {h}" for p, h in files]
    out += ["", "namespace Sts2Sim.Vec;", "",
            "public static partial class EventOptionVars",
            "{",
            "    /// <summary>Option text key (\"&lt;EVENT&gt;.pages.&lt;PAGE&gt;.options.&lt;KEY&gt;\") -> the placeholder names of its title",
            "    /// and description in order of first appearance (options without placeholders are not listed).</summary>",
            "    private static readonly (string Key, string[] Names)[] Generated =",
            "    {"]
    for key, names in table.items():
        out.append(f"        (\"{key}\", new[] {{ " + ", ".join(f"\"{n}\"" for n in names) + " }),")
    out += ["    };", "}", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed file differs")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    table, files = collect()
    text = render(table, files)
    path = Path(a.out)
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    if a.check:
        if old != text:
            sys.stdout.writelines(difflib.unified_diff(old.splitlines(True), text.splitlines(True), str(path), "generated"))
            print(f"\n{path} is stale: run sim/tools/vec/tools/gen_event_option_vars.py", file=sys.stderr)
            return 1
        print(f"{path}: up to date ({len(table)} option keys)")
        return 0
    if old != text:
        path.write_text(text, encoding="utf-8")
    print(f"wrote {path} ({len(table)} option keys with placeholders)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
