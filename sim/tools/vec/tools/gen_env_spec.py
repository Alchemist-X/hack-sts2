def _compress(names: list[str]) -> str:
    """'var_id_0, var_id_1, var_id_2, var_id_3' -> 'var_id_0..3'."""
    m = [re.fullmatch(r"(.*_)(\d+)", n) for n in names]
    if len(names) > 2 and all(m) and len({x.group(1) for x in m}) == 1:
        nums = [int(x.group(2)) for x in m]
        if nums == list(range(nums[0], nums[0] + len(nums))):
            return f"`{m[0].group(1)}{nums[0]}..{nums[-1]}`"
    return ", ".join(f"`{n}`" for n in names)


def _range(text: str, schema) -> str:
    def sub(mt):
        tok = mt.group(1)
        if tok.startswith("v:"):
            kind = tok[2:]
            return f"`{kind}` id 0..{len(schema.vocab.lists[kind]) - 1}"
        if tok.startswith("e:"):
            name = tok[2:]
            return f"`{name}` 0..{len(schema.vocab.enums[name]) - 1}"
        if tok == "cv":
            return f"`card_vars` id 0..{len(schema.card_vars) - 1}"
        if tok == "prb":
            return "bits " + " ".join(f"{k}={v}" for k, v in schema.playable_reason_bits.items() if v)
        if tok == "kw":
            return "bit 1<<k, k = `CardKeyword`"
        if tok == "st":
            return "bit flags"
        raise KeyError(tok)
    return re.sub(r"\{([^}]+)\}", sub, text)


def render(schema) -> str:
    from sts2vec.schema import Status

    names = [b.name for b in schema.buffers]
    missing = [n for n in names if n not in DESCR]
    extra = [n for n in DESCR if n not in names]
    if missing or extra:
        raise SystemExit(f"gen_env_spec: buffers without a description {missing}; described but not in schema {extra}")
    sha = hashlib.sha256(schema.text.encode("utf-8")).hexdigest()[:16]
    vocab = ", ".join(f"`{k}` {len(v)}" for k, v in schema.vocab.lists.items())
    out = [BEGIN, "",
           f"Schema: `encoder_version` **`{schema.encoder_version}`** (verified: {schema.verify_version()}), schema JSON "
           f"sha256 `{sha}`, {len(schema.buffers)} buffers, {schema.bytes_per_env:,} bytes per env "
           f"({schema.observation_bytes_per_env:,} in `obs`). Vocabularies (id 0 = none, 1 = unknown): {vocab}; "
           f"`card_vars` {len(schema.card_vars)}.", "",
           "| # | buffer | dtype [shape per env] | column(s) | range | meaning |", "| --- | --- | --- | --- | --- | --- |"]
    for b in schema.buffers:
        row_desc, cols = DESCR[b.name]
        covered: list[str] = []
        first = True
        for spec, rng, meaning in cols:
            if spec == "*":
                if b.fields is not None:
                    raise SystemExit(f"gen_env_spec: {b.name} has fields; '*' is for field-less buffers")
                col = "-"
            elif spec == "=hand":
                if tuple(b.fields or ()) != tuple(schema["hand"].fields):
                    raise SystemExit(f"gen_env_spec: {b.name} fields differ from hand")
                covered += list(b.fields)
                col = f"{len(b.fields)} columns of `hand`"
            else:
                fs = [f.strip() for f in spec.split(",")]
                unknown = [f for f in fs if f not in (b.fields or ())]
                if unknown:
                    raise SystemExit(f"gen_env_spec: {b.name}: described columns {unknown} are not in the schema")
                covered += fs
                col = _compress(fs)
            shape = "[" + ", ".join(str(x) for x in b.shape) + "]" if b.shape else "[]"
            lead = (f"| {b.index} | `{b.name}` | {b.dtype.name} {shape} — {row_desc} " if first else "| | | ")
            out.append(f"{lead}| {col} | {_range(rng, schema)} | {meaning} |")
            first = False
        if b.fields is not None:
            unc = [f for f in b.fields if f not in covered]
            dup = sorted({f for f in covered if covered.count(f) > 1})
            if unc or dup:
                raise SystemExit(f"gen_env_spec: {b.name}: undescribed columns {unc}, described twice {dup}")
    out += ["", "Enum values (`schema.vocab.enums[name][value]`):", ""]
    for name, values in schema.vocab.enums.items():
        out.append(f"- `{name}`: " + ", ".join(f"{i} {v or '∅'}" for i, v in enumerate(values)))
    out += ["", "Status bits (`status`, `sts2vec.STATUS`): "
            + ", ".join(f"`{n}` {int(v)}" for n, v in Status.__members__.items()) + ".", "", END]
    return "\n".join(out)


def splice(text: str, block: str) -> str:
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < 0 or j < i:
        raise SystemExit(f"gen_env_spec: markers not found in the spec ({BEGIN!r} ... {END!r})")
    return text[:i] + block + text[j + len(END):]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--spec", default=str(SPEC))
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed block differs from the schema")
    a = ap.parse_args(argv)
    from sts2vec import load, schema_of

    schema = schema_of(load())
    path = Path(a.spec)
    text = path.read_text(encoding="utf-8")
    new = splice(text, render(schema))
    if a.check:
        if new != text:
            sys.stdout.writelines(difflib.unified_diff(text.splitlines(True), new.splitlines(True), str(path), "generated"))
            print(f"\n{path} is stale: run sim/tools/vec/tools/gen_env_spec.py", file=sys.stderr)
            return 1
        print(f"{path}: generated block up to date ({schema.encoder_version})")
        return 0
    if new != text:
        path.write_text(new, encoding="utf-8")
    print(f"wrote {path} ({len(new.splitlines())} lines, encoder_version {schema.encoder_version})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
